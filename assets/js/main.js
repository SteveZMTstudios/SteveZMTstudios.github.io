// Hero Section Scroll Effect
document.addEventListener('DOMContentLoaded', function() {
    const hero = document.querySelector('.hero');
    const header = document.querySelector('header');
    
    if (!hero || !header) return;

    function updateHeroVars() {
        // Only active on desktop (width > 768px)
        if (window.innerWidth <= 768) {
            hero.style.removeProperty('--hero-progress');
            hero.style.removeProperty('--header-height');
            return;
        }

        const headerHeight = header.offsetHeight;
        const windowHeight = window.innerHeight;
        const scrollY = window.scrollY;
        
        // Scroll threshold to complete the animation
        const scrollThreshold = windowHeight * 0.6; 
        
        const progress = Math.min(scrollY / scrollThreshold, 1);
        
        hero.style.setProperty('--header-height', `${headerHeight}px`);
        hero.style.setProperty('--hero-progress', progress);
    }

    // Use requestAnimationFrame for smooth performance
    let ticking = false;
    window.addEventListener('scroll', () => {
        if (!ticking) {
            window.requestAnimationFrame(() => {
                updateHeroVars();
                ticking = false;
            });
            ticking = true;
        }
    });

    // Handle resize
    window.addEventListener('resize', updateHeroVars);

    // Initial call
    updateHeroVars();
});

// Hero typing effect (content comes from site.yml via data-typing-lines)
(function initHeroTyping() {
    const element = document.getElementById('typing-text');
    if (!element) return;

    let lines = [];
    try {
        lines = JSON.parse(element.getAttribute('data-typing-lines') || '[]');
    } catch (error) {
        lines = [];
    }
    if (!Array.isArray(lines) || lines.length === 0) return;

    if (window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
        element.textContent = lines[lines.length - 1];
        return;
    }

    // Type, hold, delete, then move to the next line.
    let lineIndex = 0;
    let charIndex = 0;
    let deleting = false;

    function tick() {
        // A wedged kernel cannot keep animating the hero copy.
        if (document.documentElement.classList.contains('rm-frozen')) return;

        const line = lines[lineIndex] || '';

        if (!deleting) {
            charIndex++;
            element.textContent = line.slice(0, charIndex);
            if (charIndex === line.length) {
                deleting = true;
                window.setTimeout(tick, 1500);
                return;
            }
            window.setTimeout(tick, 70);
            return;
        }

        charIndex--;
        element.textContent = line.slice(0, charIndex);
        if (charIndex === 0) {
            deleting = false;
            lineIndex = (lineIndex + 1) % lines.length;
            window.setTimeout(tick, 300);
            return;
        }
        window.setTimeout(tick, 35);
    }

    tick();
})();

// Terminal is loaded on first use to keep the homepage bundle small
const terminalToggle = document.getElementById('terminal-toggle');
let terminalLoadPromise = null;

function loadTerminal() {
    if (terminalLoadPromise) return terminalLoadPromise;

    terminalLoadPromise = new Promise((resolve, reject) => {
        const script = document.createElement('script');
        script.src = 'assets/js/terminal.js' + (SITE_VERSION ? '?v=' + encodeURIComponent(SITE_VERSION) : '');
        script.onload = () => {
            if (!window.SiteTerminal) {
                reject(new Error('terminal.js loaded without SiteTerminal'));
                return;
            }
            window.SiteTerminal.init({
                translations,
                getLang: () => currentLang,
                getRepos: () => cachedRepos,
                themeToggle,
                langToggle
            });
            resolve(window.SiteTerminal);
        };
        script.onerror = () => reject(new Error('Failed to load terminal.js'));
        document.body.appendChild(script);
    }).catch((error) => {
        console.error('Terminal load error:', error);
        if (terminalToggle) {
            terminalToggle.setAttribute('title', 'Terminal failed to load');
            terminalToggle.setAttribute('aria-label', 'Terminal failed to load');
        }
        throw error;
    });

    return terminalLoadPromise;
}

if (terminalToggle) {
    terminalToggle.addEventListener('click', () => {
        // Ignore repeat clicks while the module is still downloading.
        if (!window.SiteTerminal && terminalLoadPromise) return;
        loadTerminal().then((terminal) => terminal.toggle()).catch(() => {});
    });
}
