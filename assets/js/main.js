function updateLanguage() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.getAttribute('data-i18n');
        const value = translations[currentLang] && translations[currentLang][key];
        if (value !== undefined) el.textContent = value;
    });
    document.documentElement.lang = currentLang === 'en' ? 'en' : 'zh-CN';
    document.documentElement.setAttribute('data-lang', currentLang);

    const title = document.querySelector('title');
    if (title) {
        const key = currentLang === 'en' ? 'en' : 'zh';
        title.textContent = title.getAttribute('data-' + key) || title.textContent;
    }

    const label = currentLang === 'en' ? '切换到中文' : 'Switch to English';
    langToggle.setAttribute('title', label);
    langToggle.setAttribute('aria-label', label);
    updateThemeLabel();

    if (cachedRepos.length > 0) renderProjects();
}

// Ripple Effect
function createRipple(event) {
    const button = event.currentTarget;
    const circle = document.createElement("span");
    const diameter = Math.max(button.clientWidth, button.clientHeight);
    const rect = button.getBoundingClientRect();
    const hasPointer = event.clientX !== 0 || event.clientY !== 0;
    const x = hasPointer ? event.clientX - rect.left : rect.width / 2;
    const y = hasPointer ? event.clientY - rect.top : rect.height / 2;

    circle.style.width = circle.style.height = `${diameter}px`;
    circle.style.left = `${x - diameter / 2}px`;
    circle.style.top = `${y - diameter / 2}px`;
    circle.classList.add("ripple");

    const ripple = button.getElementsByClassName("ripple")[0];
    if (ripple) { ripple.remove(); }
    button.appendChild(circle);
}

document.querySelectorAll('.card, .btn-icon, .fab').forEach(btn => {
    btn.addEventListener('click', createRipple);
});

