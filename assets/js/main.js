function readSetting(key) {
    try { return window.localStorage.getItem(key); } catch (e) { return null; }
}

function writeSetting(key, value) {
    try { window.localStorage.setItem(key, value); } catch (e) { /* ignore */ }
}

function normalizeLang(value) {
    return value === 'en' ? 'en' : 'zh';
}

function normalizeTheme(value) {
    return value === 'dark' ? 'dark' : 'light';
}

function updateStatsTheme() {
    const isDark = currentTheme === 'dark';
    document.querySelectorAll('.github-stats img').forEach((img) => {
        let src = img.src;
        if (isDark) {
            src = src
                .replace('theme=radical', 'theme=dark')
                .replace('title_color=006a6a', 'title_color=4edada')
                .replace('icon_color=006a6a', 'icon_color=4edada');
        } else {
            src = src
                .replace('theme=dark', 'theme=radical')
                .replace('title_color=4edada', 'title_color=006a6a')
                .replace('icon_color=4edada', 'icon_color=006a6a');
        }
        if (src !== img.src) img.src = src;
    });
}

function updateThemeLabel() {
    const isZh = currentLang === 'zh';
    const label = currentTheme === 'dark'
        ? (isZh ? '切换到浅色模式' : 'Switch to light mode')
        : (isZh ? '切换到深色模式' : 'Switch to dark mode');
    themeToggle.setAttribute('title', label);
    themeToggle.setAttribute('aria-label', label);
}

function applyTheme(theme) {
    currentTheme = normalizeTheme(theme);
    document.documentElement.setAttribute('data-theme', currentTheme);
    const icon = themeToggle.querySelector('.material-symbols-outlined');
    if (icon) icon.textContent = currentTheme === 'light' ? 'dark_mode' : 'light_mode';
    updateThemeLabel();
    updateStatsTheme();
}

